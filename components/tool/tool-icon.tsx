export function getToolIcon(name: string): LucideIcon {
  return ICONS[name] ?? Wrench;
}

export function ToolIcon({ name, ...props }: { name: string } & LucideProps) {
  // createElement with a looked-up (static, module-level) component, so the
  // icon is not mistaken for a component defined during render.
  return createElement(getToolIcon(name), { "aria-hidden": true, ...props });
}
